// Embeds the optimized model portraits so built-in avatars also work offline.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(import.meta.dirname, '..')
const ASSETS = join(ROOT, 'assets/model-avatars')
const OUTPUT = join(ROOT, 'modules/bot-runtime/product-overlay/files/src/client/model-avatar-catalog.js')

export async function generateModelAvatarCatalog({ check = false } = {}) {
  const manifest = JSON.parse(await readFile(join(ASSETS, 'generation-manifest.json'), 'utf8'))
  assert.equal(manifest.schemaVersion, 1, 'unsupported model-avatar manifest')
  const ids = new Set(), images = new Set(), entries = []
  let imageBytes = 0
  for (const item of manifest.items) {
    assert.match(item.id, /^[a-z][a-z0-9-]+$/)
    assert.ok(!ids.has(item.id), `duplicate model avatar: ${item.id}`)
    assert.equal(item.image, `${item.id}.webp`, 'avatar image must stay within the asset directory')
    assert.ok(typeof item.label === 'string' && item.label.length > 0, `missing label: ${item.id}`)
    const bytes = await readFile(join(ASSETS, item.image))
    assert.equal(bytes.toString('ascii', 0, 4), 'RIFF', `${item.id}: expected WebP`)
    assert.equal(bytes.toString('ascii', 8, 12), 'WEBP', `${item.id}: expected WebP`)
    assert.ok(bytes.length <= 120 * 1024, `${item.id}: exceeds the Host avatar byte limit`)
    const sha256 = createHash('sha256').update(bytes).digest('hex')
    assert.equal(sha256, item.imageSha256, `${item.id}: image differs from its generation manifest`)
    assert.ok(!images.has(sha256), `duplicate portrait: ${item.id}`)
    const image = `data:image/webp;base64,${bytes.toString('base64')}`
    assert.ok(image.length < 160000, `${item.id}: exceeds the Bot state avatar limit`)
    entries.push({ id: item.id, label: item.label, image })
    ids.add(item.id); images.add(sha256); imageBytes += bytes.length
  }
  assert.ok(entries.length > 0, 'model avatar catalog is empty')
  const code = '// Generated by scripts/build-model-avatar-catalog.mjs; do not edit by hand.\n'
    + '// Source images and prompts: assets/model-avatars/generation-manifest.json.\n'
    + `export const MODEL_AVATARS = Object.freeze([\n${entries.map(entry => `  Object.freeze(${JSON.stringify(entry)})`).join(',\n')}\n])\n`
  if (check) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '')
    assert.equal(current.replace(/\r\n/g, '\n'), code, 'model avatar catalog is stale; run node scripts/build-model-avatar-catalog.mjs')
  } else {
    await mkdir(dirname(OUTPUT), { recursive: true })
    await writeFile(OUTPUT, code)
  }
  return { status: 'passed', avatars: entries.length, imageBytes }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await generateModelAvatarCatalog({ check: process.argv.includes('--check') })))
}
