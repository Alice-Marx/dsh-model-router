  await capture('chat-settings-model-picker')
  await page.locator('[data-model-choice="fixture/writing-model"]').click()
  assert.equal(await page.evaluate(() => window.__chatSettingsFixture.calls.length), 1)
  await page.getByRole('button', { name: '保存绑定', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.bb-feedback[data-kind="saved"]')?.textContent.includes('设置已保存'))
  const calls = await page.evaluate(() => window.__chatSettingsFixture.calls)
  assert.deepEqual(calls.map(call => call.action), ['binding.inspect', 'binding.save', 'binding.inspect'])
  assert.equal(calls[1].payload.expectedRevision, 1); assert.deepEqual(calls[1].payload.settings.model, { provider: 'fixture', model: 'writing-model' })
  checks.push('a model choice stays local until explicit save; the acknowledged save rereads the original Bot without starting a task')
  await page.getByRole('tab', { name: '身份与个性' }).click()
  await page.locator('#bp-profile-research-instructions').waitFor()
  await page.locator('#bp-profile-research-role').fill('梳理研究证据')
  await page.locator('#bp-profile-research-instructions').fill('先核对原始来源；有疑问时说明。')
  await page.getByRole('tab', { name: '模型与工具' }).click()
  await page.getByRole('tab', { name: '身份与个性' }).focus()
  await page.keyboard.press('End')
  assert.equal(await page.locator('#bp-profile-research-role').inputValue(), '梳理研究证据')
  assert.deepEqual(await page.evaluate(() => window.__chatSettingsFixture.calls.map(call => call.action)), ['binding.inspect', 'binding.save', 'binding.inspect', 'botProfile.inspect'])
  await capture('chat-settings-identity-wide')
  await page.getByRole('button', { name: '保存身份与指令', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.bp-profile-feedback[data-kind="saved"]'))
  const profileCalls = await page.evaluate(() => window.__chatSettingsFixture.calls)
  assert.equal(profileCalls.length, 5); assert.equal(profileCalls[4].action, 'botProfile.save')
  assert.deepEqual(profileCalls[4].payload.profile, { role: '梳理研究证据', instructions: '先核对原始来源；有疑问时说明。' })
  checks.push('the actual settings drawer lazily loads identity, retains unsaved text across tabs, and explicitly saves only edited profile fields')
  await page.getByRole('tab', { name: '模型与工具' }).click()
  await page.getByLabel('关闭 Bot 设置').click()
  assert.equal(await page.locator('[data-chat-command="model"]').evaluate(node => document.activeElement === node), true)
  await page.setViewportSize({ width: 375, height: 900 })
  await page.locator('[data-chat-command="model"]').click(); await page.locator('.bb-root').waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await capture('chat-settings-phone')
  await page.evaluate(() => document.body.setAttribute('data-bp-appearance', 'dark')); await capture('chat-settings-phone-dark')
  await page.getByRole('tab', { name: '身份与个性' }).click()
  await page.locator('#bp-profile-research-instructions').waitFor()
  assert.equal(await page.locator('#bp-profile-research-instructions').inputValue(), '先核对原始来源；有疑问时说明。')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await capture('chat-settings-identity-phone-dark')
  await page.evaluate(() => document.body.setAttribute('data-bp-appearance', 'light'))
  await capture('chat-settings-identity-phone-light')
  await page.evaluate(() => document.body.setAttribute('data-bp-appearance', 'dark'))
  await page.getByRole('tab', { name: '模型与工具' }).click()
  checks.push('identity edits reopen from the synthetic committed response and both 375px appearances fit the actual settings drawer')
  await page.locator('.bp-model-picker-trigger').click(); await page.getByLabel('搜索可用模型').waitFor({ state: 'visible' })
  assert.equal(await page.getByLabel('搜索可用模型').evaluate(node => document.activeElement === node), true)
