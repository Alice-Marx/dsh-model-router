  assert.equal(await page.locator('.bp-model-popover').count(), 0); assert.equal(await page.locator('.bp-bot-settings-dialog').count(), 1)
  await page.keyboard.press('Escape'); assert.equal(await page.locator('.bp-bot-settings-dialog').count(), 0)
  checks.push('375px light/dark settings have no horizontal overflow; nested Escape closes the picker before the settings drawer and restores chat focus')
  assert.deepEqual(errors, []); assert.ok(requests.every(url => url.startsWith(fixture.url)))
  const report = { status: 'passed', checks, images, pageErrors: errors, limitation: 'Actual product chat, settings and model-picker components with synthetic owner responses; no live Host/profile/CLI/model.' }
  await writeFile(join(output, 'report.json'), JSON.stringify(report, null, 2) + '\n'); console.log(JSON.stringify(report, null, 2))
